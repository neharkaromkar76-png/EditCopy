    init {
        // Seed curated pro templates on startup
        scope.launch {
            seedDefaultTemplatesIfEmpty()
        }
    }

    val allTemplates: Flow<List<VideoTemplate>> = templateDao.getAllTemplates().map { entities ->
        entities.map { it.toDomainModel() }
    }

    val favoriteTemplates: Flow<List<VideoTemplate>> = templateDao.getFavoriteTemplates().map { entities ->
        entities.map { it.toDomainModel() }
    }

    val userTemplates: Flow<List<VideoTemplate>> = templateDao.getUserCreatedTemplates().map { entities ->
        entities.map { it.toDomainModel() }
    }

    suspend fun getTemplateById(id: String): VideoTemplate? {
        val entity = templateDao.getTemplateById(id)
        return entity?.toDomainModel()
    }

    suspend fun toggleFavorite(id: String, currentFavorite: Boolean) {
        templateDao.updateFavorite(id, !currentFavorite)
    }

    suspend fun renameTemplate(id: String, newTitle: String) {
        templateDao.renameTemplate(id, newTitle)
    }

    suspend fun duplicateTemplate(template: VideoTemplate): VideoTemplate {
        val duplicated = template.copy(
            id = UUID.randomUUID().toString(),
            title = "${template.title} (Copy)",
            isUserCreated = true,
            isFavorite = false
        )
        templateDao.insertTemplate(duplicated.toEntity())
        return duplicated
    }

    suspend fun saveTemplate(template: VideoTemplate) {
        templateDao.insertTemplate(template.toEntity())
    }

    suspend fun deleteTemplate(id: String) {
        templateDao.deleteTemplateById(id)
    }

    private suspend fun seedDefaultTemplatesIfEmpty() {
        val existing = templateDao.getTemplateById(DEFAULT_TEMPLATES[0].id)
        if (existing == null) {
            templateDao.insertAll(DEFAULT_TEMPLATES.map { it.toEntity() })
        }
    }

