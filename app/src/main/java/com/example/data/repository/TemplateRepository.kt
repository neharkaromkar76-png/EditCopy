// Extension mappers between Entity and Domain model
private fun TemplateEntity.toDomainModel(): VideoTemplate {
    val category = runCatching { TemplateCategory.valueOf(categoryName) }.getOrDefault(TemplateCategory.TRENDING)
    val tagsList = if (tagsCsv.isBlank()) emptyList() else tagsCsv.split(",")
    return VideoTemplate(
        id = id,
        title = title,
        description = description,
        category = category,
        durationSeconds = durationSeconds,
        aspectRatio = aspectRatio,
        cutsCount = cutsCount,
        keyframesCount = keyframesCount,
        zoomCount = zoomCount,
        hasBeatSync = hasBeatSync,
        hasAudioTrack = hasAudioTrack,
        creator = creator,
        tags = tagsList,
        isFavorite = isFavorite,
        isUserCreated = isUserCreated,
        primaryAccentColorHex = primaryAccentColorHex,
        secondaryAccentColorHex = secondaryAccentColorHex,
        bpm = bpm,
        clipSlots = deserializeSlots(slotsJson)
    )
}

private fun VideoTemplate.toEntity(): TemplateEntity {
    return TemplateEntity(
        id = id,
        title = title,
        description = description,
        categoryName = category.name,
        durationSeconds = durationSeconds,
        aspectRatio = aspectRatio,
        cutsCount = cutsCount,
        keyframesCount = keyframesCount,
        zoomCount = zoomCount,
        hasBeatSync = hasBeatSync,
        hasAudioTrack = hasAudioTrack,
        creator = creator,
        isFavorite = isFavorite,
        isUserCreated = isUserCreated,
        tagsCsv = tags.joinToString(","),
        primaryAccentColorHex = primaryAccentColorHex,
        secondaryAccentColorHex = secondaryAccentColorHex,
        bpm = bpm,
        slotsJson = serializeSlots(clipSlots)
    )
}

// Lightweight slot serializer without needing reflection or heavy json runtime
private fun serializeSlots(slots: List<ClipSlot>): String {
    return slots.joinToString(";") { slot ->
        "${slot.slotIndex}|${slot.label}|${slot.durationSeconds}|${slot.transitionIn ?: ""}|${slot.speedFactor}|${slot.keyframeEffect ?: ""}"
    }
}

private fun deserializeSlots(raw: String): List<ClipSlot> {
    if (raw.isBlank()) return emptyList()
    return raw.split(";").mapNotNull { part ->
        val tokens = part.split("|")
        if (tokens.size >= 6) {
            ClipSlot(
                slotIndex = tokens[0].toIntOrNull() ?: 1,
                label = tokens[1],
                durationSeconds = tokens[2].toFloatOrNull() ?: 1.0f,
                transitionIn = tokens[3].ifBlank { null },
                speedFactor = tokens[4].toFloatOrNull() ?: 1.0f,
                keyframeEffect = tokens[5].ifBlank { null }
            )
        } else null
    }
}
